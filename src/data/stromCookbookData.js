// Helper: search across recipes and memories
export function searchCookbook(query = '', sectionId = 'all') {
  const q = query.trim().toLowerCase();
  
  let recipeMatches = COOKBOOK_RECIPES;
  let memoryMatches = COOKBOOK_MEMORIES;

  if (sectionId !== 'all') {
    if (sectionId === 'memories') {
      recipeMatches = [];
    } else {
      recipeMatches = recipeMatches.filter(r => r.sectionId === sectionId);
      memoryMatches = [];
    }
  }

  if (q) {
    recipeMatches = recipeMatches.filter(r => 
      r.title.toLowerCase().includes(q) ||
      r.contributor.toLowerCase().includes(q) ||
      (r.story && r.story.toLowerCase().includes(q)) ||
      r.ingredients.some(ing => ing.toLowerCase().includes(q)) ||
      r.instructions.some(inst => inst.toLowerCase().includes(q))
    );

    memoryMatches = memoryMatches.filter(m =>
      m.title.toLowerCase().includes(q) ||
      m.contributor.toLowerCase().includes(q) ||
      (m.story && m.story.toLowerCase().includes(q)) ||
      m.text.some(t => t.toLowerCase().includes(q))
    );
  }

  return {
    recipes: recipeMatches,
    memories: memoryMatches,
    totalCount: recipeMatches.length + memoryMatches.length
  };
}

// Helper: get an item by ID
export function getCookbookItemById(id) {
  if (!id) return null;
  const memory = COOKBOOK_MEMORIES.find(m => m.id === id);
  if (memory) return { ...memory, isMemory: true };
  const recipe = COOKBOOK_RECIPES.find(r => r.id === id);
  if (recipe) return { ...recipe, isRecipe: true };
  return null;
}
